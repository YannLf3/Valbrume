TOP = 3      # lignes réservées aux accents des capitales
CAP = 7
DESC = 2
CELL_H = TOP + CAP + DESC   # 12
BASE = TOP + CAP            # 10
LINE_H = CELL_H + 1


def _rows(spec: str) -> List[str]:
    return spec.split("/")


def glyph_grid(ch: str) -> List[List[int]]:
    """Grille CELL_H × largeur du glyphe."""
    rows = _rows(G[ch])
    w = max(len(r) for r in rows)
    grid = [[0] * w for _ in range(CELL_H)]
    for j, r in enumerate(rows):
        for i, c in enumerate(r):
            if c == "#":
                grid[TOP + j][i] = 1
    return grid


def composed_grid(base: str, accent: str) -> List[List[int]]:
    grid = glyph_grid(base)
    acc = ACCENTS[accent]
    upper = base.isupper()
    if base == "i":  # sans point, élargi pour porter l'accent
        grid = [[0, 0, 0] for _ in range(CELL_H)]
        for j in range(2, 7):
            grid[TOP + j][1] = 1
    w = len(grid[0])
    aw = len(acc[0])
    if aw > w:
        pad = aw - w
        grid = [r + [0] * pad for r in grid]
        w = aw
    ox = (w - aw) // 2
    top = 0 if upper else TOP - 1
    for j, r in enumerate(acc):
        for i, c in enumerate(r):
            if c == "#":
                grid[top + j][ox + i] = 1
    return grid


def cedilla(base: str) -> List[List[int]]:
    grid = glyph_grid(base)
    w = len(grid[0])
    mid = w // 2
    grid[TOP + 7][mid] = 1
    grid[TOP + 8][mid - 1] = 1
    return grid


def all_glyphs() -> Dict[str, List[List[int]]]:
    out: Dict[str, List[List[int]]] = {ch: glyph_grid(ch) for ch in G}
    for ch, base, acc in COMPOSED:
        out[ch] = composed_grid(base, acc)
    out["ç"] = cedilla("c")
    out["Ç"] = cedilla("C")
    out[" "] = glyph_grid(" ")
    out[" "] = [[0] for _ in range(CELL_H)]
    return out


def write_font(name: str, scale: int) -> int:
    glyphs = all_glyphs()
    chars = sorted(glyphs.keys(), key=ord)
    atlas_w = 256
    x = y = 0
    places: List[Tuple[str, int, int, int]] = []
    for ch in chars:
        w = len(glyphs[ch][0])
        if x + w + 1 > atlas_w // scale:
            x = 0
            y += CELL_H + 1
        places.append((ch, x, y, w))
        x += w + 1
    atlas_h = 1
    while atlas_h < (y + CELL_H + 1) * scale:
        atlas_h *= 2
    img = Image.new("RGBA", (atlas_w // scale, atlas_h // scale), (0, 0, 0, 0))
    for ch, gx, gy, w in places:
        grid = glyphs[ch]
        for j in range(CELL_H):
            for i in range(w):
                if grid[j][i]:
                    img.putpixel((gx + i, gy + j), (255, 255, 255, 255))
    if scale > 1:
        img = img.resize((atlas_w, atlas_h), Image.NEAREST)
    os.makedirs(OUT, exist_ok=True)
    img.save(os.path.join(OUT, name + ".png"))
    lines = [
        'info face="Valbrume Pixel" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0' % (CELL_H * scale),
        "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0" % (LINE_H * scale, BASE * scale, atlas_w, atlas_h),
        'page id=0 file="%s.png"' % name,
        "chars count=%d" % len(places),
    ]
    for ch, gx, gy, w in places:
        lines.append(
            "char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15"
            % (ord(ch), gx * scale, gy * scale, w * scale, CELL_H * scale, (w + 1) * scale)
        )
    with open(os.path.join(OUT, name + ".fnt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return len(places)


def main() -> int:
    n = write_font("valbrume", 1)
    write_font("valbrume_big", 2)
    return n


